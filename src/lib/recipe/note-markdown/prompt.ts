/**
 * AI 用プロンプトの文面（#214）
 *
 * AI と相談して決めたレシピを、パーサが読める Markdown で出力させるための文面。
 * Web（#178）と LINE（#201）で同じものを使う。LINE の返信は1通5000文字までなので短く保つ。
 *
 * 文面のルールはパーサの挙動と1対1で対応している。仕様（docs/NOTE_MARKDOWN_FORMAT.md）や
 * パーサを変えたら、ここも見直すこと。出力例はパーサに通るかを単体テストで確かめている。
 */
import { RECIPE_INPUT_END_MARKER, RECIPE_INPUT_PREFIX } from './prefix'

const FENCE = '```'

/** 文面に載せる出力例。接頭語と終端マーカーも含めて、AI にそのまま真似させる形 */
export const RECIPE_PROMPT_EXAMPLE = [
  RECIPE_INPUT_PREFIX,
  '# 鶏むね肉のレモン蒸し',
  '調理時間: 20分',
  '',
  '## 材料（2人分）',
  '- 鶏むね肉 300g',
  '- レモン 1/2個',
  '### たれ',
  '- 醤油 大さじ1',
  '- はちみつ 小さじ2',
  '',
  '## 手順',
  '1. 鶏むね肉をそぎ切りにして塩をふる',
  '2. 耐熱皿に並べ、レモンをのせてラップをし、600Wで6分加熱する',
  '3. たれを混ぜてかける',
  '',
  '## メモ',
  '冷蔵で2日もつ',
  RECIPE_INPUT_END_MARKER,
].join('\n')

/**
 * コードブロックで出力させるのは、AI の画面から長押しでコピーするとレンダリング後の文字列になり、
 * `#` や `-` が落ちて見出し・材料を読めなくなるため。コードブロックならコピーボタンで生の Markdown が取れる
 * （パーサはフェンスも前後の言葉も切り落とす）。
 * 出力例は行頭に接頭語を持つので、文面そのものを LINE に送ると出力例がレシピとして読まれる。
 */
export const RECIPE_NOTE_PROMPT = [
  'ここまでの会話で決めたレシピを、次のルールで出力してください。',
  '',
  'ルール:',
  '- コードブロック1つだけを出力する。前置きや締めの言葉は書かない',
  `- コードブロックの1行目は「${RECIPE_INPUT_PREFIX}」、最後の行は「${RECIPE_INPUT_END_MARKER}」にする`,
  '- 表は使わない。材料は「- 名前 分量」の箇条書きで、1行に1つ書く',
  '- 見出しは「# 料理名」「## 材料（◯人分）」「## 手順」「## メモ」だけを使う。名前を変えたり、ほかの見出しを足したりしない',
  '- 合わせ調味料などをまとめるときは、「## 材料」の中に「### たれ」のような小見出しを置く',
  '- 調理時間は料理名の次の行に「調理時間: ◯分」と書く',
  '- 手順は「1.」から始まる番号付きリストにする',
  '- メモ（保存方法やコツ）が無ければ「## メモ」ごと省く',
  '',
  '出力例:',
  FENCE,
  RECIPE_PROMPT_EXAMPLE,
  FENCE,
].join('\n')
