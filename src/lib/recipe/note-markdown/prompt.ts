/**
 * AI 用プロンプトの文面（#214）
 *
 * AI と相談して決めたレシピを、パーサが読める Markdown で出力させるための文面。
 * Web（#178）と LINE（#201）で同じものを使う。LINE の返信は1通5000文字までなので短く保つ。
 *
 * 文面のルールはパーサの挙動と1対1で対応している。仕様（docs/NOTE_MARKDOWN_FORMAT.md）や
 * パーサを変えたら、ここも見直すこと。出力例はパーサに通るかを単体テストで確かめている。
 * パーサがこのファイルの出力例を参照するので、ここからパーサを import しない（循環する）。
 */
import { RECIPE_INPUT_END_MARKER, RECIPE_INPUT_PREFIX } from './prefix'

const FENCE = '```'

/** 文面に載せる出力例。接頭語と終端マーカーも含めて、AI にそのまま真似させる形 */
export const RECIPE_PROMPT_EXAMPLE = [
  RECIPE_INPUT_PREFIX,
  '# 鶏むね肉のレモン蒸し',
  '調理時間: 20分',
  '',
  '## 材料（2人分）',
  '- 鶏むね肉 300g',
  '- レモン 1/2個',
  '### たれ',
  '- 醤油 大さじ1',
  '- はちみつ 小さじ2',
  '',
  '## 手順',
  '1. 鶏むね肉をそぎ切りにして塩をふる',
  '2. 耐熱皿に並べ、レモンをのせてラップをし、600Wで6分加熱する',
  '3. たれを混ぜてかける',
  '',
  '## メモ',
  '冷蔵で2日もつ',
  RECIPE_INPUT_END_MARKER,
].join('\n')

/**
 * コードブロックで出力させるのは、AI の画面から長押しでコピーするとレンダリング後の文字列になり、
 * `#` や `-` が落ちて見出し・材料を読めなくなるため。コードブロックならコピーボタンで生の Markdown が取れる
 * （パーサはフェンスも前後の言葉も切り落とす）。
 * 出力例は行頭に接頭語を持つので、文面そのものを送り返すと出力例が読まれる。出力例と同じ料理は
 * パーサが登録を止める（parse-recipe-markdown.ts の isPromptExample）。
 *
 * 文面は LINE の「書式を見る」で人にもそのまま見せる（#201）。AI への語りかけ（「ここまでの会話で」など）は書かず、
 * 書式と例だけにする。冒頭の1文は、AI に貼ったときに何をするかが伝わるよう残している。
 */
export const RECIPE_NOTE_PROMPT = [
  'レシピを次の書式で書いてください。',
  '',
  '書式:',
  `- 全体をコードブロック（${FENCE}）1つで囲み、前後に別の文を書かない`,
  `- 1行目は「${RECIPE_INPUT_PREFIX}」、最後の行は「${RECIPE_INPUT_END_MARKER}」`,
  '- 見出しは「# 料理名」「## 材料（◯人分）」「## 手順」「## メモ」だけ。名前を変えたり、ほかの見出しを足したりしない',
  '- 調理時間は料理名の次の行に「調理時間: ◯分」',
  '- 材料は「- 名前 分量」の箇条書きで、1行に1つ。表は使わない',
  '- 材料の名前は食材名だけにし、括弧で補足を付けない（「酢（リンゴ酢がおすすめ）」ではなく「酢」）。補足はメモに書く',
  '- 合わせ調味料などは、「## 材料」の中に「### たれ」のような小見出しでまとめる',
  '- 手順は「1.」から始まる番号付きリスト',
  '- メモ（保存方法やコツ）が無ければ「## メモ」ごと省く',
  '',
  '例（形式の見本です。料理名・材料・手順・メモは、書きたいレシピの内容にしてください）:',
  FENCE,
  RECIPE_PROMPT_EXAMPLE,
  FENCE,
].join('\n')
